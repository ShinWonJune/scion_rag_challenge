#!/usr/bin/env python3
"""Generate answers for two retrieval strategies and capture token/latency cost.

Arm A (dense_top5):  gte dense retrieval top-5  -> LLM
Arm B (rerank_top3): gte dense top-5 -> dragonkue rerank -> top-3 -> LLM

Both arms reuse exp9 retrieval (41Q, gte encoder) so the ONLY variable is the
rerank step + context size. Answers are generated by gpt-oss-20b via the vLLM
OpenAI-compatible server; per-question prompt/completion/total tokens and
wall-clock latency are recorded for a cost comparison.

Output: experiments/outputs/exp_answer_quality_judge/{dense_top5,rerank_top3}/
        final/{qid}.json   (+ gen_summary.json per arm)
"""
from __future__ import annotations

import json
import os
import sys
import time
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO))

from shrag.prompts.general.generate_answer_base_v3 import build_prompt  # noqa: E402
from openai import OpenAI  # noqa: E402

VLLM_URL = os.environ.get("VLLM_BASE_URL", "http://10.38.38.40:8004/v1")
VLLM_MODEL = os.environ.get("VLLM_MODEL", "openai/gpt-oss-20b")
MAX_ANSWER_TOKENS = 4000  # match e2e baseline (run_manifest cli_args)
CONCURRENCY = 8

GOLD = REPO / "experiments/gold_scienceon/artifacts/scienceon_gold_full_only.jsonl"
ARMS = {
    "dense_top5": REPO / "experiments/outputs/exp9_rerank_top3_vllm/retrieval/cases/E9_dense_top5/retrieval.jsonl",
    "rerank_top3": REPO / "experiments/outputs/exp9_rerank_top3_vllm/retrieval/cases/E9_rerank_c5_out3/retrieval.jsonl",
}
OUT_ROOT = REPO / "experiments/outputs/exp_answer_quality_judge"


def load_jsonl(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def load_questions() -> dict[str, str]:
    return {str(r["qid"]): r["question"] for r in load_jsonl(GOLD)}


def load_retrieval(path: Path) -> dict[str, list[dict]]:
    return {str(r["question_id"]): r["hits"] for r in load_jsonl(path)}


def build_context_payload(qid: str, question: str, hits: list[dict]) -> dict:
    """Replicate the pipeline's generate.py context structure."""
    return {
        "id": qid,
        "retrieval_results": [
            {"query": question, "query_meta": {"type": "original"}, "hits": hits}
        ],
    }


def generate_one(client: OpenAI, qid: str, question: str, hits: list[dict]) -> dict:
    payload = build_context_payload(qid, question, hits)
    context_str = json.dumps(payload, ensure_ascii=False, indent=2)
    prompt = build_prompt(question, context_str)

    t0 = time.perf_counter()
    resp = client.chat.completions.create(
        model=VLLM_MODEL,
        messages=[{"role": "user", "content": prompt}],
        max_tokens=MAX_ANSWER_TOKENS,
        temperature=0.0,
    )
    latency = time.perf_counter() - t0
    answer = (resp.choices[0].message.content or "").strip()
    usage = resp.usage
    return {
        "id": qid,
        "question_id": qid,
        "question": question,
        "result": answer,
        "answer": answer,
        "prompt": prompt,
        "model": VLLM_MODEL,
        "prompt_type": "general",
        "used_context": [
            {"doc_id": h.get("doc_id", ""), "rank": h.get("rank"), "from_step": "step4"}
            for h in hits
        ],
        "retrival": payload,
        "usage": {
            "prompt_tokens": usage.prompt_tokens,
            "completion_tokens": usage.completion_tokens,
            "total_tokens": usage.total_tokens,
        },
        "gen_latency_sec": round(latency, 4),
        "n_context_docs": len(hits),
    }


def run_arm(arm: str, retr_path: Path, questions: dict[str, str]) -> dict:
    hits_by_qid = load_retrieval(retr_path)
    qids = [q for q in questions if q in hits_by_qid]
    final_dir = OUT_ROOT / arm / "final"
    final_dir.mkdir(parents=True, exist_ok=True)
    client = OpenAI(base_url=VLLM_URL, api_key="token-abc123")

    results: dict[str, dict] = {}
    arm_t0 = time.perf_counter()
    with ThreadPoolExecutor(max_workers=CONCURRENCY) as ex:
        futs = {
            ex.submit(generate_one, client, qid, questions[qid], hits_by_qid[qid]): qid
            for qid in qids
        }
        for fut in as_completed(futs):
            qid = futs[fut]
            rec = fut.result()
            results[qid] = rec
            (final_dir / f"{qid}.json").write_text(
                json.dumps(rec, ensure_ascii=False, indent=2), encoding="utf-8"
            )
            print(f"[{arm}] q{qid} done  ctx={rec['n_context_docs']} "
                  f"tok(p/c/t)={rec['usage']['prompt_tokens']}/"
                  f"{rec['usage']['completion_tokens']}/{rec['usage']['total_tokens']} "
                  f"{rec['gen_latency_sec']}s")
    wall = time.perf_counter() - arm_t0

    n = len(results)
    s_prompt = sum(r["usage"]["prompt_tokens"] for r in results.values())
    s_comp = sum(r["usage"]["completion_tokens"] for r in results.values())
    s_total = sum(r["usage"]["total_tokens"] for r in results.values())
    s_lat = sum(r["gen_latency_sec"] for r in results.values())
    summary = {
        "arm": arm,
        "n_questions": n,
        "n_context_docs_mean": round(sum(r["n_context_docs"] for r in results.values()) / n, 3),
        "prompt_tokens_total": s_prompt,
        "prompt_tokens_mean": round(s_prompt / n, 1),
        "completion_tokens_total": s_comp,
        "completion_tokens_mean": round(s_comp / n, 1),
        "total_tokens_total": s_total,
        "total_tokens_mean": round(s_total / n, 1),
        "gen_latency_sec_mean": round(s_lat / n, 4),
        "gen_latency_sec_sum_serial": round(s_lat, 2),
        "wall_clock_sec_parallel": round(wall, 2),
        "max_answer_tokens": MAX_ANSWER_TOKENS,
        "model": VLLM_MODEL,
    }
    (OUT_ROOT / arm / "gen_summary.json").write_text(
        json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    print(f"\n=== {arm} summary ===\n{json.dumps(summary, ensure_ascii=False, indent=2)}\n")
    return summary


def main() -> None:
    questions = load_questions()
    print(f"server={VLLM_URL} model={VLLM_MODEL} | {len(questions)} questions")
    summaries = {}
    for arm, path in ARMS.items():
        summaries[arm] = run_arm(arm, path, questions)
    (OUT_ROOT / "gen_summary_both.json").write_text(
        json.dumps(summaries, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    print("ALL GENERATION DONE")


if __name__ == "__main__":
    main()
